/**
 * Closing line of the on-screen / printed TIS report. With firm branding set it
 * credits the firm; without it, the product — by the region-neutral name the
 * site uses everywhere else (index.html title, site nav and footer).
 */
import { isFirmConfigured, type FirmBranding } from "@/lib/firm-branding";

export const PRODUCT_NAME = "Simple Impact Studies";

export function TisReportFooter({ firm }: { firm: FirmBranding }) {
  return (
    <footer className="text-xs text-muted-foreground text-center pt-4 border-t">
      {isFirmConfigured(firm) ? (
        <>
          Prepared by <span className="font-semibold">{firm.firmName}</span>
          {firm.preparedBy && <> · {firm.preparedBy}</>}
          {firm.peNumber && <> · {firm.peNumber}</>}
        </>
      ) : (
        <>
          Screening-level TIS generated by {PRODUCT_NAME}.
          A formal submittal requires Synchro/SimTraffic validation with measured turning-movement counts.
        </>
      )}
    </footer>
  );
}
